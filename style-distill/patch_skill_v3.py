from pathlib import Path

SK = Path("style-distill/_skill/style-distill").resolve()


class Patcher:
    def __init__(self, name: str):
        self.path = SK / name
        self.t = self.path.read_text(encoding="utf-8")
        self.n = 0

    def rep(self, old: str, new: str) -> None:
        assert self.t.count(old) == 1, f"[{self.path.name}] 锚点未唯一命中({self.t.count(old)}): {old[:40]!r}"
        self.t = self.t.replace(old, new, 1)
        self.n += 1

    def append(self, text: str) -> None:
        self.t = self.t.rstrip() + "\n\n" + text.strip() + "\n"
        self.n += 1

    def save(self) -> None:
        self.path.write_text(self.t, encoding="utf-8")
        print(f"  {self.path.name}: 应用 {self.n} 处，现 {len(self.t.splitlines())} 行")


