"""由 v9 生成 v10：中间那一格改回"全身动态"（像图2 中间那个全身像）。

代价与对策（必须一起做）：
  取消"裁到腰以上"就会重新暴露**下装的信息缺口**——当初之所以裁掉，就是因为输入裁到胸口以上、
  模型看不到下半身，于是每版都自己编（背带短裤→白裙→衬衫长裤→白短裤）。
  对策：**把下装明确指定**（不是留给模型发挥）。
  依据：用户给的 R1 里她穿橙白百褶裙；而设定写她初中是"篮球队啦啦队长、舞蹈团团长"——
  百褶裙有据。灰度化后是中灰，与白上衣、黑领结形成三层明度，正好。
锚点由 grep 得来。
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE / "prompt_threeview_v9.txt").read_text(encoding="utf-8")
src_len = len(t)


def rep(old: str, new: str) -> None:
    global t
    assert t.count(old) == 1, f"锚点未唯一命中({t.count(old)}): {old[:44]}"
    t = t.replace(old, new, 1)


# ---- 1) 结构：中间改回全身 ----
rep("框内三个视图：左＝半身、中＝**半身动态（裁到腰部以上）**、右＝**偏侧的头肩像**，**都是同一个人**，服装与配饰在三处完全一致。",
    "框内三个视图：左＝半身、中＝**全身动态**、右＝**偏侧的头肩像**，**都是同一个人**，服装与配饰在三处完全一致。")

rep("· 三个视图都要**被外框裁到**：左侧半身的**下半身被画面下缘切掉**、**中间那一格裁到腰部以上、不出现腿与下装**、右侧头肩像的**顶部与右侧仍被外框裁掉一点**；",
    "· 三个视图都要**被外框裁到**：左侧半身的**下半身被画面下缘切掉**、"
    "**中间那一格是全身、脚接近或越过画面下缘**、右侧头肩像的**顶部与右侧仍被外框裁掉一点**；")

rep("· **三格的尺度只差一点，保持中等偏小**：左侧半身与右侧头肩像**大小接近**，中间那一格**略小一号**。"
    "**不要出现占画面高度一半以上的大头特写**、**不要任何一格变成半页特写**；但也不要三格完全一样大、不要三格的头顶在同一水平线上。",
    "· **三格的尺度**：中间那一格是**全身**（三人里最高、最瘦长），左侧半身与右侧头肩像**大小接近**。"
    "**不要出现占画面高度一半以上的大头特写**、**不要任何一格变成半页特写**。")

# ---- 2) 中间那格的姿态：恢复全身、并指定下装 ----
rep("中间·半身动态（这一格必须与左右两格是**同一个人、同一套服装**，不要变成另一个人）：**取景裁到腰部以上，不要出现腿、不要出现下装（裙或裤）**；**一只手五指张开向外伸出、另一只手半握或收在胸前**——**不要两只手都五指全张、不要两只手一样大、不要两只手对称**；身体向一侧扭转、上半身略后仰；头略微抬起看向观者。",
    "中间·**全身动态**（这一格必须与左右两格是**同一个人、同一套服装**，不要变成另一个人）："
    "**取景是全身——从头顶到脚都要在画面里**（脚接近或越过画面下缘）。\n"
    "　· 姿态：**一条腿屈膝、小腿向后抬起、脚离地**，另一条腿直立承重、脚尖点地；"
    "双臂向两侧张开、手掌朝外；身体向一侧扭转、上半身略后仰；头略微抬起看向观者。\n"
    "　· **一只手五指张开向外伸出、另一只手半握或收在胸前**——"
    "**不要两只手都五指全张、不要两只手一样大、不要两只手对称**。\n"
    "　· **下装（必须照这条画，不要自己改）**：一条**百褶短裙**，颜色为中灰（比白上衣深、比黑领结浅），"
    "裙摆有规则的竖向褶；裙长在膝盖上方。**不要长裤、不要牛仔裤、不要长裙、不要背带、不要腰带、不要纽扣排**。\n"
    "　· 腿与脚：**光腿或很短的素色袜**，脚上穿**简单的素色低帮鞋**（不要长靴、不要带蝴蝶结的鞋）。")

# ---- 3) 负向 ----
rep("**尺度**：不要大头特写、不要让任何一格占到画面高度的一半以上、不要把右侧那格画成半页特写；",
    "**尺度**：不要大头特写、不要让任何一格占到画面高度的一半以上、不要把右侧那格画成半页特写；"
    "不要让中间那格又变回半身、不要把中间那格的腿裁掉；\n"
    "**中间那格的下装**：不要长裤、不要牛仔裤、不要长裙、不要短裤、不要背带、不要腰带、不要纽扣排、"
    "不要提到膝盖以上的裙摆、不要长靴、不要带蝴蝶结的鞋、不要让两腿的姿势对称；")

out = HERE / "prompt_threeview_v10.txt"
out.write_text(t, encoding="utf-8")
print(f"wrote {out.name}  {src_len} -> {len(t)} chars")
for k in ["中＝**全身动态**", "百褶短裙", "从头顶到脚都要在画面里",
          "不要把中间那格的腿裁掉", "不要提到膝盖以上的裙摆", "背景**大面积纯白**"]:
    print(f"  {'OK  ' if k in t else 'MISS'} {k}")
