"""由 v12B 生成 v13：保留 B 的动作神态，新增一个「整体调子」模块把画面调淡。

依据（只读实测）：
  A/B/C 三版提示词**只差中间那格的表情一句**，所以深浅差属**模型方差**，不是写出来的。
  指标剖面（B → C）：纸白 0.604→0.670、灰调 0.232→0.179、墨量 0.061→0.040、平均亮度 0.842→0.881、对比跨度 0.698→0.590。
  即"淡" = 纸白更多、中间调网点更少、大块深灰更少、对比更收。
所以本版把 C 的观感**翻译成可写的规则**加进去，其余逐字继承 v12B（含 B 的动作神态与跳出框架四条几何关系）。
锚点全部来自 grep。
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE / "prompt_threeview_v12B.txt").read_text(encoding="utf-8")
src_len = len(t)


def rep(old: str, new: str) -> None:
    global t
    assert t.count(old) == 1, f"锚点未唯一命中({t.count(old)}): {old[:44]}"
    t = t.replace(old, new, 1)


# ---- 1) 在「背景」块之后插入「整体调子」块 ----
OLD1 = "（判断标准：把画面缩小看，背景应当是白的；如果缩略图上背景是灰的，就是画脏了。）"
NEW1 = OLD1 + """

【整体调子：必须"淡"（本版重点）】
这一页要读起来像**浅色调的原稿页**，而不是"铺满网点的灰页"：
· 画面**以白为主**，大面积留白；亮部要占绝大多数；
· **网点只用在该暗的地方**（例如衣料内侧的深褶、裙子的暗面），**中间调尽量不铺网点**；
· 头发的排线**疏一些**，排线之间**多留亮部**，整束头发读起来是**浅灰**的，不要密到发深；
· **不要出现大块的深灰**；不要为了表现体积而把一大片区域铺上网点；
· 全画面**近黑的只有少数几处**——黑领结、瞳孔、以及衣料上本来就很深的那几条带；
  其余一切保持浅色；
· 头发、皮肤、白色衣料、裙子的受光面都要**接近留白**。
· **但黑领结与瞳孔仍要保持近黑**——它们不能被"调淡"一起冲掉。

（判断标准：把整页缩到很小看，它应当是**偏白的**，只看到几处深色的点和线；如果整页读起来是灰的，就是调子太深了。）"""
rep(OLD1, NEW1)

# ---- 2) 负向补一条 ----
OLD2 = "**手稿感（限域）**：不要光滑到没有笔迹的数码感、不要全程等粗的线条；**但也不要把手稿感画成加线**——不要背景排线、不要交叉涂线、不要背景成片灰调、不要草稿式乱线、不要斜线阴影；"
NEW2 = OLD2 + "\n" + (
    "**调子太深（本版重点）**：不要铺满网点、不要把中间调铺成大片灰、不要大块深灰或大块黑色、"
    "不要让头发密到发黑、不要把皮肤或白色衣料铺上网点、不要让整页读起来是灰的；"
    "**但黑领结与瞳孔仍要保持近黑**；")
rep(OLD2, NEW2)

out = HERE / "prompt_threeview_v13.txt"
out.write_text(t, encoding="utf-8")
print(f"wrote {out.name}  {src_len} -> {len(t)} chars")
for k in ["【整体调子：必须", "中间调尽量不铺网点", "近黑的只有少数几处",
          "黑领结与瞳孔仍要保持近黑", "调子太深（本版重点）",
          "张嘴笑、露出虎牙", "百褶短裙", "跳出框架"]:
    print(f"  {'OK  ' if k in t else 'MISS'} {k}")
