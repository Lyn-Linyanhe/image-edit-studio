"""由 v4 生成 v5。

依据百度百科查到的角色设定（引自《龙族Ⅱ：悼亡者之瞳》）修正三处：
  1) **发型**：设定明写"束着长长的高马尾""蓬松的刘海仿佛云雾"——我们前四版全是披发，是差得最远的一项；
  2) **面部**：设定明写"脸颊有些婴儿肥""嘴角还有小虎牙""长长的睫毛"——
     同时把比例从"通用萌系幼儿"拉回"青年"（收眼睛、下巴不缩短、头身比收紧）；
     注意：**不是去掉可爱**，而是把可爱落在设定指定的部位（马尾/虎牙/婴儿肥），不要落在"比例幼儿化"上；
  3) **中间那一格改成腰以上取景**：下装的信息缺口（我把输入裁到胸口以上造成的）直接不存在了。
其余逐字继承 v4 —— 特别是【背景·大面积纯白】与身份参考块，那是已经做对的地方。
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE / "prompt_threeview_v4.txt").read_text(encoding="utf-8")
src_len = len(t)


def rep(old: str, new: str) -> None:
    global t
    assert old in t, f"锚点没命中: {old[:40]}"
    t = t.replace(old, new, 1)


# ---- 1) 脸型 / 眼睛 / 发型 三条重写 ----
rep("· **脸型**：偏圆的鹅蛋脸、下巴收得短而圆；",
    "· **脸型（青年比例，不要幼儿化）**：脸宽约为脸高的四分之三；下巴收窄但**不缩短**，下颌线清楚；"
    "**脸颊有婴儿肥（有肉感），但不要因此把脸画圆、画短**；")
rep("· **眼睛**：眼型偏圆、上眼睑睫毛线较粗、眼尾略微下垂；眼内高光小而准；",
    "· **眼睛（关键）**：眼高约为脸高的**五分之一**、形状**横向偏长**；上眼睑睫毛线清晰、睫毛**长**；"
    "眼瞳清澈光润；眼内高光小而准。**不要大圆眼、不要让眼睛占到脸高的三分之一**；"
    "鼻子要有一定长度，五官纵向铺开，不要挤在脸的下半中央；")
rep("· **发型**：长直发偏厚、额前碎发多且成组、两侧有长鬓发垂到胸前；发梢细而分股；",
    "· **发型（设定明写，三个视图都用）**：头发在**头顶偏后束成一束，扎成长长的高马尾**；"
    "马尾长、厚、蓬松，向下垂落到背部并在身后散开；发梢细而分股。"
    "**额前的刘海蓬松、层次多，像云雾一样**；鬓角只留少量碎发。"
    "**不要披发、不要把头发全部散开、不要中分长发**；")
rep("三个视图的面部**不要各画各的**，要像同一个人在三个角度上。",
    "· **表情细节**：笑的时候**嘴角要露出一颗小虎牙**；神情活泼俏皮、有亲和力。\n"
    "· **体格**：体态纤细修长、骨肉匀亭；头相对身体**略小**、脖颈略长，不要头大身短。\n"
    "三个视图的面部**不要各画各的**，要像同一个人在三个角度上。")

# ---- 2) 中间那格改取景（v4 的取景信息分散在「输出结构」块里，锚点按实际文本写）----
rep("框内三个视图：左＝半身、中＝全身、右＝大头特写",
    "框内三个视图：左＝半身、中＝**半身动态（裁到腰部以上）**、右＝大头特写")
rep("· 三个视图**互相叠压**——中间那个全身要在视觉上**压住**左侧半身的一部分（她们前后有遮挡关系）；",
    "· 三个视图**互相叠压**——中间那一格要在视觉上**压住**左侧半身的一部分（她们前后有遮挡关系）；")
rep("· 三个视图都要**被外框裁到**：左侧半身的**下半身被画面下缘切掉**、中间全身的**脚部接近或越过下缘**、右侧大头的**右侧与顶部被外框裁去一块**；",
    "· 三个视图都要**被外框裁到**：左侧半身的**下半身被画面下缘切掉**、"
    "**中间那一格裁到腰部以上、不出现腿与下装**、右侧大头的**右侧与顶部被外框裁去一块**；")
rep("中间·全身（这一格必须与左右两格是**同一个人、同一套服装**，不要变成另一个人、不要换成衬衫长裤）：动态站姿——一条腿屈膝、小腿向后抬起、脚离地，另一条腿直立承重；双臂向两侧张开，手掌朝外、手指自然张开；身体向一侧扭转、上半身略后仰；头略微抬起看向观者。",
    "中间·半身动态（这一格必须与左右两格是**同一个人、同一套服装**，不要变成另一个人）："
    "**取景裁到腰部以上，不要出现腿、不要出现下装（裙或裤）**；动势保留——"
    "双臂向两侧张开、手掌朝外、手指自然张开；身体向一侧扭转、上半身略后仰；头略微抬起看向观者。")

# ---- 3) 负向补"幼态化"与"披发" ----
rep("**面部**：不要画成与身份参考无关的通用漫画脸、不要让三个视图的脸各画各的、不要改变眼尾与睫毛的走势；",
    "**面部**：不要画成与身份参考无关的通用漫画脸、不要让三个视图的脸各画各的、不要改变眼尾与睫毛的走势；"
    "**不要幼态化比例**——不要大而圆的眼睛、不要占脸高三分之一的眼睛、不要缩短下巴、不要极短的鼻子、"
    "不要把脸画成圆脸、不要让五官挤在脸的下半中央、不要头大身短的幼儿比例；")
rep("**服装（整类禁止）**",
    "**发型**：不要披发、不要把头发全散开、不要没有马尾、不要把高马尾画成低马尾或双马尾；"
    "**取景**：中间那一格不要出现腿、不要出现下装、不要拉远成全身；\n"
    "**服装（整类禁止）**")

out = HERE / "prompt_threeview_v5.txt"
out.write_text(t, encoding="utf-8")
print(f"wrote {out.name}  {src_len} -> {len(t)} chars")
for k in ["长长的高马尾", "小虎牙", "眼高约为脸高的**五分之一**", "裁到腰部以上", "不要幼态化比例", "背景**大面积纯白**"]:
    print(f"  {'OK  ' if k in t else 'MISS'} {k}")
