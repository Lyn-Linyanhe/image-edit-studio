"""由 v10 生成 v11：让中间那一格"跳出框架"（用户新要求）。

参考图2 的做法：中间那个全身像的**双腿与脚越过页面下边框、落到框外的纸面**，
**下框线在她腿经过的地方断开（被腿遮住）**；其余三条边完整。
这就是"跳脱、打破框架"的读法，也是这一格成为视觉焦点的原因。
锚点由 grep 得来。
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE / "prompt_threeview_v10.txt").read_text(encoding="utf-8")
src_len = len(t)


def rep(old: str, new: str) -> None:
    global t
    assert t.count(old) == 1, f"锚点未唯一命中({t.count(old)}): {old[:44]}"
    t = t.replace(old, new, 1)


# ---- 1) 结构段：新增"跳出框架"这条 ----
rep("整幅是一张横向的**漫画原稿页**，外面一圈**较粗的外框线**。",
    "整幅是一张横向的**漫画原稿页**，外面一圈**较粗的外框线**。")

rep("· 三个视图都要**被外框裁到**：左侧半身的**下半身被画面下缘切掉**、"
    "**中间那一格是全身、脚接近或越过画面下缘**、右侧头肩像的**顶部与右侧仍被外框裁掉一点**；",
    "· **中间那一格要\"跳出框架\"（本版重点，最要紧的一条）**：她的**双腿与双脚越过外框的下缘线**，"
    "**落到框线之外的纸面空白上**；**外框的下缘线在腿经过的地方断开、被她的腿遮住**——"
    "也就是说下缘线不完整，中间留出被她越过的缺口。这一格因此成为整幅的视觉焦点。\n"
    "· **其余三条边框线保持完整**（左边、上边、右边）。\n"
    "· 其余两格**被外框裁到**即可：左侧半身的**下半身被画面下缘切掉**、"
    "右侧头肩像的**顶部与右侧被外框裁掉一点**；这两格**都不要越出框外**；")

# ---- 2) 尺度和前景关系 ----
rep("· **三格的尺度**：中间那一格是**全身**（三人里最高、最瘦长），左侧半身与右侧头肩像**大小接近**。"
    "**不要出现占画面高度一半以上的大头特写**、**不要任何一格变成半页特写**。",
    "· **三格的尺度**：中间那一格**最大**——全身、**占满画面高度并且下半身越出下框**；"
    "左侧半身与右侧头肩像**大小接近、都明显小于它**。"
    "**不要出现占画面高度一半以上的大头特写**、**不要把中间那格画小到看不出越界**。")

# ---- 3) 姿态段里点明"越界" ----
rep("　· 姿态：**一条腿屈膝、小腿向后抬起、脚离地**，另一条腿直立承重、脚尖点地；",
    "　· 姿态：**一条腿屈膝、小腿向后抬起、脚离地**，另一条腿直立承重、脚尖点地；"
    "**这一格的腿要伸得足够低，让小腿与脚越过外框的下缘线**；")

# ---- 4) 负向 ----
rep("**尺度**：不要大头特写、不要让任何一格占到画面高度的一半以上、不要把右侧那格画成半页特写；",
    "**跳出框架（本版重点）**：不要让外框的下缘线完整地横在她的腿前面、"
    "不要把她的脚关在框内、不要在框线处把她的腿切断、不要让下缘线穿过她的腿不断开；"
    "但也不要让左右两格越出框外、不要让上边与左右边断开；\n"
    "**尺度**：不要大头特写、不要把右侧那格画成半页特写、不要把中间那格画小；")

out = HERE / "prompt_threeview_v11.txt"
out.write_text(t, encoding="utf-8")
print(f"wrote {out.name}  {src_len} -> {len(t)} chars")
for k in ['跳出框架', '落到框线之外的纸面空白上', '下缘线在腿经过的地方断开',
          '其余三条边框线保持完整', '不要让她把脚关在框内'.replace('她',''),
          '不要让外框的下缘线完整地横在她的腿前面', '背景**大面积纯白**']:
    print(f"  {'OK  ' if k in t else 'MISS'} {k}")
