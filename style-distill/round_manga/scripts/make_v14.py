"""由 v12B 生成 v14：新增【体格与比例】模块（治"身体也幼态"）。

背景（用户的纠正）：幼态不止在脸上，也在身体上。而我此前**只在改脸**，
关于身体全篇只有一句抽象话（L23 的"头相对身体略小、脖颈略长"）——不可数、压不住模型的默认儿童比例。

实测（10 等分网格读数）：
  我们的中格：头约占全高 1/5（约 5 头身）、腿不到身高一半、肩宽仅约头宽 1.2 倍、短颈、高腰、无胯部曲线、膝踝无结构。
  参考 R1  ：头约占全高 1/7（约 7 头身）、腿超过身高一半、肩宽约头宽 2 倍、颈长清楚、腰线约 0.6、有明显胯部曲线。

修法：比例是可数的，所以**写成硬数字**而不是形容词。
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE / "prompt_threeview_v12B.txt").read_text(encoding="utf-8")
src_len = len(t)


def rep(old: str, new: str) -> None:
    global t
    assert t.count(old) == 1, f"锚点未唯一命中({t.count(old)}): {old[:44]}"
    t = t.replace(old, new, 1)


# ---- 1) 把那句抽象话换成可数的体格模块 ----
rep("· **体格**：体态纤细修长、骨肉匀亭；头相对身体**略小**、脖颈略长，不要头大身短。",
    "· **体格与比例（本版重点，照数字画，不要凭感觉）**——这一角色是**大学一年级的青年女性**，"
    "体态纤细修长，**绝不是幼态体型**：\n"
    "　　**头身比**：全高约为 **7 个头高**（头高约为身高的 **1/7**，不是 1/5）；**不要大头小身**；\n"
    "　　**腿**：从胯到脚约为身高的 **一半或略多**，腿要**长**；小腿明显长于大腿的视觉印象不要反过来；\n"
    "　　**肩**：肩宽约为**头宽的 1.8–2 倍**，肩线**平**、不要溜肩塌肩；\n"
    "　　**颈**：有**明显可见的颈长**，约为头高的 1/3，不要短颈；\n"
    "　　**腰**：腰线在身高约 **0.6** 处（**不要高腰**），腰细但要有转折；\n"
    "　　**胯**：**有胯部曲线**，裙摆下方能看出胯的宽度；\n"
    "　　**关节**：膝、踝、腕都要有**骨点与转折**，**不要把四肢画成直筒**；\n"
    "　　**手**：手指**细长**、有指节与腕骨，不要圆头圆手；\n"
    "　　**整体**：站姿重心稳、躯干与四肢的长度关系是成人比例；**不要头大肩窄的幼儿体型**。")

# ---- 2) 负向补 ----
rep("**尺度**：不要大头特写",
    "**体格（本版重点）**：不要大头小身、不要画成 5 头身、不要窄肩溜肩、不要短颈、"
    "不要高腰、不要没有胯部曲线、不要把腿画成两根直筒、不要没有膝踝结构、不要圆头圆手、"
    "不要把四肢画得又短又粗、不要头大肩窄的幼儿体型；\n"
    "**尺度**：不要大头特写")

out = HERE / "prompt_threeview_v14.txt"
out.write_text(t, encoding="utf-8")
print(f"wrote {out.name}  {src_len} -> {len(t)} chars")
for k in ["**体格与比例（本版重点，照数字画", "全高约为 **7 个头高**", "肩宽约为**头宽的 1.8–2 倍**",
          "腰线在身高约 **0.6** 处", "不要把四肢画成直筒", "不要画成 5 头身"]:
    print(f"  {'OK  ' if k in t else 'MISS'} {k}")
