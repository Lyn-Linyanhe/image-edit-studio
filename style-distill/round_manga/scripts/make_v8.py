"""由 v7 生成 v8：路线② —— 去掉大头特写，三格都取中等偏小的尺度（单变量）。

目的：验证"脸不像夏弥"是不是**尺度**造成的。
v7 的实测规律：三格里只有那个**大头**跑成了模型的默认脸，而两个小尺寸视图明显更贴参考。
所以这一版把"右侧大头特写"降级成"头肩像"，三格尺度只保留轻微差别。

注意与 v6 的关系：v6 是为了治"死板"而**拉大**尺度差。本版只收回"极端的那一档"（大头特写），
**表情／视线／姿态／头饰的差异全部保留**——死板不会回来，因为那几条不是靠尺度差撑的。
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE / "prompt_threeview_v7.txt").read_text(encoding="utf-8")
src_len = len(t)


def rep(old: str, new: str) -> None:
    global t
    assert t.count(old) == 1, f"锚点未唯一命中({t.count(old)}): {old[:44]}"
    t = t.replace(old, new, 1)


# ---- 1) 右侧那格从"大头特写"降为"头肩像" ----
rep("框内三个视图：左＝半身、中＝**半身动态（裁到腰部以上）**、右＝大头特写",
    "框内三个视图：左＝半身、中＝**半身动态（裁到腰部以上）**、右＝**偏侧的头肩像**")

# ---- 2) 尺度：只留轻微差别，不要极端 ----
rep("· **三格的个头必须差得很大**：右侧大头**最大**（占画面高度的一半以上，并被右侧与顶部外框切掉一块）；"
    "左侧半身**中等**；中间那一格**最小**（像远景一样，整体比左右两格都小一号）。"
    "**绝对不要把三格画成一样大、不要三格的头顶在同一水平线上。**",
    "· **三格的尺度只差一点，保持中等偏小**：左侧半身与右侧头肩像**大小接近**，中间那一格**略小一号**。"
    "**不要出现占画面高度一半以上的大头特写**、**不要任何一格变成半页特写**；"
    "但也不要三格完全一样大、不要三格的头顶在同一水平线上。")

# ---- 3) 裁切表述 ----
rep("、右侧大头的**右侧与顶部被外框裁去一块**；",
    "、右侧头肩像的**顶部与右侧仍被外框裁掉一点**；")

# ---- 4) 姿态那格改名 ----
rep("右侧·大头：**身体侧转约四分之三**（不要正面朝前）；",
    "右侧·头肩像（**不要画成大头特写**）：**身体侧转约四分之三**（不要正面朝前）；")

# ---- 5) 负向 ----
rep("**死板**：不要把三格画成同一套模板的三份拷贝",
    "**尺度**：不要大头特写、不要让任何一格占到画面高度的一半以上、不要把右侧那格画成半页特写；\n"
    "**死板**：不要把三格画成同一套模板的三份拷贝")

out = HERE / "prompt_threeview_v8.txt"
out.write_text(t, encoding="utf-8")
print(f"wrote {out.name}  {src_len} -> {len(t)} chars")
for k in ["右＝**偏侧的头肩像**", "不要出现占画面高度一半以上的大头特写",
          "三格的尺度只差一点", "不要大头特写、不要让任何一格",
          "三格的表情必须各不相同", "不要三格都是笑脸"]:
    print(f"  {'OK  ' if k in t else 'MISS'} {k}")
print(f"  残留'大头特写'（应只在负向里出现）: {t.count('大头特写')} 处")
