"""由 v6 生成 v7：把投喂从"三图"改成"两图"，把省下的字节全给身份参考图。

根因（本轮用户纠正后的诊断）：
  用户说的是"人物的**面部**不符合夏弥参考图"，不是版式死板。
  而面部不像的技术原因是——三图投喂超限，压缩梯子把身份参考压成
  **448px + 高斯模糊 1.2 + 量化 128 色**；被抹掉的正好是脸部细节。
  模型拿不到"她的脸长什么样"，就退回自己的默认脸。

本版做法：
  1) **删掉画法图**（画法用文字描述已经足够细），改成两图：内容图 + 身份参考图；
  2) 两图合计 1.27 MiB（内容 0.69 + 身份长边900灰度 0.58），**在预算内 → 梯子走"原样"档 →
     身份参考不被压缩**，脸部细节得以保留；
  3) 全文把"画法图"的引用改成"以下文字描述的画法"，并把面部约束提到最前、语气加重。
锚点全部从 v6 真实文本 grep 得来。
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE / "prompt_threeview_v6.txt").read_text(encoding="utf-8")
src_len = len(t)


def rep(old: str, new: str) -> None:
    global t
    assert t.count(old) == 1, f"锚点未唯一命中({t.count(old)}): {old[:44]}"
    t = t.replace(old, new, 1)


# ---- 1) 三图 → 两图；画法改为纯文字 ----
rep("上传三张图：第一张是【内容图】（人物、身份、服饰与配件的主要来源，也是要被修改的那张）；"
    "第二张是【画法图】（提供线条、明暗、细节密度的画法，以及本轮要模仿的动作与版式）；"
    "第三张是【身份参考图】（**只提供这个角色的长相**：脸型、眼睛与睫毛的走势、发型轮廓与发量、"
    "头顶那套饰物的构成；**不提供**它的画法、构图、服装与配色）。",
    "上传两张图：第一张是【内容图】（服饰、配件、道具与场景结构的主要来源，也是要被修改的那张）；"
    "第二张是【身份参考图】（**这个角色的长相**：脸型、眼睛与睫毛的形状、鼻子与嘴的形状、"
    "发型轮廓与发量；**不提供**它的画法、构图、服装与配色）。\n"
    "**本轮最重要的一条约束就是面部**：三个视图的脸都必须像第二张图，"
    "**不要用你自己的默认脸型**。画法（线条与明暗）由下面的文字描述给出，不再投喂画法参考图。")
rep("不得从画法图挪用它的角色、服饰、道具或文字。",
    "不得从身份参考图挪用它的服装、场景或配色；它的角色长相是本轮唯一的身份依据。")

# ---- 2) 身份参考块的表述 ----
rep("【身份参考（本版新增，三个视图都要满足）】",
    "【身份参考（本版最重要，三个视图都要满足）】")
rep("第三张图是**同一个角色的清晰正面像**，用来锁定\"她长什么样\"。三个视图的脸都照它来：",
    "第二张图是**同一个角色的清晰正面像**，用来锁定\"她长什么样\"。"
    "**三个视图的脸型、五官形状都要照它来，不要各画各的、也不要画成模型自己的默认脸**：")

rep("2 **面部要贴第三张身份参考图**：脸型、眼型、眼尾与睫毛的走势都照它来，三个视图保持一致；脸颊用斜向排线表示红晕。",
    "2 **面部必须贴第二张身份参考图**（本版重点）：脸型、眼型、眼尾与睫毛的形状、鼻子的长度与位置、"
    "嘴的形状，全部照它来；三个视图保持一致；脸颊用斜向排线表示红晕。")

# ---- 3) 画法段的来源改为文字 ----
rep("【画 法（照画法图）】", "【画 法（按下面的文字描述，不再投喂画法参考图）】")
rep("DETAIL：细节密度向画法图看齐——蕾丝、荷叶边、缎带、手套、衣料褶皱都用细线一层层勾出来。",
    "DETAIL：细节密度要高——蕾丝、荷叶边、缎带、手套、衣料褶皱都用细线一层层勾出来。")
rep("SCOPE：画法图只提供上述画法、动作与版式；**不提供**它的角色、服饰、道具或文字。",
    "SCOPE：本轮的画法全部来自上面这段文字描述；身份只来自第二张图的长相。"
    "不要引入任何其它角色、服饰、道具或页面版式。")
rep("【背景（本版重点：必须回到画法图那样的\"干净\"）】",
    "【背景（必须保持干净）】")
rep("不要保留人物图的**上下两格**与分格线；不要任何**字幕或对白文字**；不要人物图中间那块**橙色的圆润物**（它是什么**未识别**）；不要人物图上方那两条**贯穿画面的斜带**；不要画法图的手写标注、页边批注与日文假名。",
    "不要保留人物图的**上下两格**与分格线；不要任何**字幕或对白文字**；不要人物图中间那块**橙色的圆润物**（它是什么**未识别**）；不要人物图上方那两条**贯穿画面的斜带**；不要手写标注、页边批注与日文假名。")

# ---- 4) 负向加重面部 ----
rep("**面部**：不要画成与身份参考无关的通用漫画脸、不要让三个视图的脸各画各的、不要改变眼尾与睫毛的走势；",
    "**面部（本版重点）**：不要画成模型自己的默认漫画脸、不要画成与第二张图无关的通用脸、"
    "不要让三个视图的脸各画各的、不要改变眼型与眼尾、睫毛、鼻形与嘴形的走势；")

out = HERE / "prompt_threeview_v7.txt"
out.write_text(t, encoding="utf-8")
print(f"wrote {out.name}  {src_len} -> {len(t)} chars")
for k in ["上传两张图", "本轮最重要的一条约束就是面部", "第二张图是**同一个角色的清晰正面像**",
          "不再投喂画法参考图", "不要画成模型自己的默认漫画脸", "背景**大面积纯白**"]:
    print(f"  {'OK  ' if k in t else 'MISS'} {k}")
print(f"  残留的'画法图'引用数（应为 0）: {t.count('画法图')}")
