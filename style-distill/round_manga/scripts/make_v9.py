"""由 v8 生成 v9：拉开三格的**发型细节**与**头饰佩戴状态**（单变量）。

用户反馈："现在画像已经可以了，但是三个视角的人物发型配饰等过于相近。"
诊断：三格的马尾**束法与走向几乎一样**，头饰又是**同一套、同一摆法**（云朵饰带＋发夹＋向日葵＋太阳镜，
三格都端端正正架在头顶）→ 又回到"盖章"感。

一个有用的判断：**图1 那套头饰是那场戏的配件，不是她每场都戴的**——
用户给的 R1 只有太阳镜（啦啦队造型），R2 只有一朵小花发饰。所以"三格佩戴状态不同"更贴设定。

原则（关键，写进提示词）：**差别放在"可变的造型状态"上**（马尾束法／走向、头饰佩戴、角度、表情），
**而不是放在"脸的形状与角色特征"上**——后者一变就会变成"三个人"（v4→v5 那段踩过）。
锚点全部由 grep 得来。
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE / "prompt_threeview_v8.txt").read_text(encoding="utf-8")
src_len = len(t)


def rep(old: str, new: str) -> None:
    global t
    assert t.count(old) == 1, f"锚点未唯一命中({t.count(old)}): {old[:44]}"
    t = t.replace(old, new, 1)


# ---- 1) 把"三格不要摆得一模一样"升级成"三格佩戴状态各不相同 + 马尾束法不同" ----
rep("· **头顶那套饰物（三格不要摆得一模一样）**：至少有一格让一部分头发挡住它，"
    "或者让它的角度与被外框裁切的程度不同；不要三格都端端正正地摆出同一个花环。"
    "构成是：一条云朵状的饰带横在头顶，饰带上方有两枚并排的小发夹（一枚偏粉、一枚偏蓝），",
    "· **三格的发型束法与走向必须各不相同（本版重点）**：三格都保持\"高马尾\"这个设定，"
    "但束法要不一样——左侧＝扎得高而紧、马尾直挺贴着后脑；中间＝扎得**松**、马尾**甩向身体一侧**、"
    "有几缕头发散落出来；右侧＝扎得**略低的高马尾**、马尾**垂到肩前**搭在一侧。"
    "**不要把三格的马尾画成同一个束法、同一个走向、同一个垂落方向**；"
    "但也不要改成双马尾、披发、丸子头或短发。\n"
    "· **三格的头饰佩戴状态必须各不相同（本版重点）**：这些头饰是那一场戏的配件，不是每场都戴——\n"
    "　　左侧＝**全戴**：云朵饰带＋两枚发夹＋向日葵，太阳镜**架在头顶**（与内容图一致）；\n"
    "　　中间＝**只把太阳镜拉到额前压住刘海**，**不戴**云朵饰带与向日葵（头发上只留少量发夹）；\n"
    "　　右侧＝**只戴云朵饰带与向日葵**，**不戴太阳镜**。\n"
    "　　**不要三格都戴齐同一套、不要三格都把太阳镜架在头顶同一个位置。**\n"
    "· 头饰的构成（戴上时）：一条云朵状的饰带横在头顶，饰带上方有两枚并排的小发夹（一枚偏粉、一枚偏蓝），")

# ---- 2) 负向补充 ----
rep("**死板**：不要把三格画成同一套模板的三份拷贝",
    "**三格的造型相近（本版重点）**：不要把三格的马尾画成同一束法、同一走向、同一垂落方向；"
    "不要让三格都戴齐同一套头饰、不要让三格都把太阳镜架在头顶的同一位置；"
    "但也不要因此把某个视图改成双马尾、披发、丸子头或短发；\n"
    "**死板**：不要把三格画成同一套模板的三份拷贝")

out = HERE / "prompt_threeview_v9.txt"
out.write_text(t, encoding="utf-8")
print(f"wrote {out.name}  {src_len} -> {len(t)} chars")
for k in ["三格的发型束法与走向必须各不相同", "三格的头饰佩戴状态必须各不相同",
          "只把太阳镜拉到额前压住刘海", "不戴太阳镜", "不要把三格的马尾画成同一束法"]:
    print(f"  {'OK  ' if k in t else 'MISS'} {k}")
