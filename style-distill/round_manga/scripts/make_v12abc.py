"""由 v11 生成 A/B/C 三版：只改"中间那一格的表情"这一个变量。

背景：用户问"是否又出现过于幼态"，对齐比较确认**只有中间那一格幼**——机制是
"张嘴大笑"会把眼睛放大、脸颊推圆（v8 那轮已诊断过一次，这次复现）。
所以三版沿同一条轴排开：**年龄感 ↔ 活跃度**。
   A 闭嘴微笑露虎牙   —— 不触发夸张，年龄感与另两格一致（首选）
   B 张嘴笑但眼型解耦 —— 保留活跃感，用指令压住眼睛
   C 不笑、半阖眼侧视 —— 脸最稳，活泼感交给身体动势
其余一切逐字继承 v11（含"跳出框架"那四条几何写法）。
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
base = (HERE / "prompt_threeview_v11.txt").read_text(encoding="utf-8")

OLD = "· **三格的表情必须各不相同，不要三格都是笑脸**：左侧＝半阖眼、平静、**不笑**；中间＝**张嘴大笑**、露出虎牙；右侧＝慵懒含笑、**不露齿**。"
assert base.count(OLD) == 1, f"锚点未唯一命中: {base.count(OLD)}"

VARIANTS = {
    "A": "· **三格的表情必须各不相同，不要三格都是笑脸**：左侧＝半阖眼、平静、**不笑**；"
         "中间＝**闭嘴微笑、嘴角露出一颗虎牙**——**不要张嘴、不要大笑、不要因为笑就把眼睛画大**；"
         "右侧＝慵懒含笑、**不露齿**。",
    "B": "· **三格的表情必须各不相同，不要三格都是笑脸**：左侧＝半阖眼、平静、**不笑**；"
         "中间＝**张嘴笑、露出虎牙**，但**眼睛必须保持与左右两格相同的细长半阖形状——"
         "眼高仍约为脸高的五分之一、横向偏长；不要因为张嘴就把眼睛画大、不要把虹膜和高光放大、不要把脸颊推圆**；"
         "右侧＝慵懒含笑、**不露齿**。",
    "C": "· **三格的表情必须各不相同，不要三格都是笑脸**：左侧＝半阖眼、平静、**不笑**；"
         "中间＝**不笑**——半阖眼、视线略偏向一侧，**脸的年龄感与左右两格完全一致，"
         "活泼感全部由身体动势（抬腿、张开双臂、身体扭转）提供，不要用表情去补**；"
         "右侧＝慵懒含笑、**不露齿**。",
}

for k, v in VARIANTS.items():
    t = base.replace(OLD, v, 1)
    out = HERE / f"prompt_threeview_v12{k}.txt"
    out.write_text(t, encoding="utf-8")
    print(f"wrote {out.name}  {len(t)} chars")
    print(f"   {'OK  ' if '跳出框架' in t and '百褶短裙' in t else 'MISS'} 继承检查（跳出框架 + 百褶短裙）")
