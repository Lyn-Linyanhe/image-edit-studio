"""由 v5 生成 v6：治"死板"。

诊断：死板不来自画法，来自**三格差异太小**——
  ① 三格个头接近（都是头肩大小）→ 读成"三连拍"；
  ② 三格都是笑脸 → 表情无变化；
  ③ 每格都是标准姿势，中间那格两只手都五指全张且一样大；
  ④ 头饰三格一模一样 → "盖章"感。
对照图2 为什么活：右侧大头占半页、中间那格最小、表情与视线各不相同。
所以本版只做一件事：**把三格之间的差异拉开**（尺度／表情／视线／姿态／头饰角度），画法与背景不动。
锚点全部从 v5 的真实文本 grep 得来（见上一轮教训）。
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE / "prompt_threeview_v5.txt").read_text(encoding="utf-8")
src_len = len(t)


def rep(old: str, new: str) -> None:
    global t
    assert t.count(old) == 1, f"锚点未唯一命中({t.count(old)}): {old[:44]}"
    t = t.replace(old, new, 1)


# ---- 1) 拉开尺度：三格个头差别要大 ----
rep("· 三个视图的**角度各不相同**：左侧偏四分之三侧脸、中间正面、右侧偏四分之三侧脸。",
    "· 三个视图的**角度各不相同**：左侧偏四分之三侧脸、中间正面、右侧偏四分之三侧脸；\n"
    "· **三格的个头必须差得很大**：右侧大头**最大**（占画面高度的一半以上，并被右侧与顶部外框切掉一块）；"
    "左侧半身**中等**；中间那一格**最小**（像远景一样，整体比左右两格都小一号）。"
    "**绝对不要把三格画成一样大、不要三格的头顶在同一水平线上。**")

# ---- 2) 表情与视线各异 ----
rep("· **表情细节**：笑的时候**嘴角要露出一颗小虎牙**；神情活泼俏皮、有亲和力。",
    "· **表情细节**：笑的时候**嘴角要露出一颗小虎牙**；神情活泼俏皮、有亲和力。\n"
    "· **三格的表情必须各不相同，不要三格都是笑脸**：左侧＝半阖眼、平静、**不笑**；"
    "中间＝**张嘴大笑**、露出虎牙；右侧＝慵懒含笑、**不露齿**。\n"
    "· **三格的视线各不相同**：左侧看向**画外左侧**、中间看向**观者**、右侧视线**略偏下**。")

# ---- 3) 姿态：去掉"标准姿势"，破坏对称 ----
rep("左侧·半身：一只手抬到头侧、接近耳上方的位置，手肘向外打开；头略微倾斜；另一只手按在胸前衣料上；视线看向观者或略偏下方。",
    "左侧·半身：一只手抬到额侧、手指自然搭在眼镜边上（像随手扶了一下）；"
    "身体略微倾斜、**一侧肩膀高一侧肩膀低**；**另一只手不要摆造型**——自然垂在身侧。"
    "头向抬起的那一侧倾斜。")
rep("中间·半身动态（这一格必须与左右两格是**同一个人、同一套服装**，不要变成另一个人）：**取景裁到腰部以上，不要出现腿、不要出现下装（裙或裤）**；动势保留——双臂向两侧张开、手掌朝外、手指自然张开；身体向一侧扭转、上半身略后仰；头略微抬起看向观者。",
    "中间·半身动态（这一格必须与左右两格是**同一个人、同一套服装**，不要变成另一个人）："
    "**取景裁到腰部以上，不要出现腿、不要出现下装（裙或裤）**；"
    "**一只手五指张开向外伸出、另一只手半握或收在胸前**——"
    "**不要两只手都五指全张、不要两只手一样大、不要两只手对称**；"
    "身体向一侧扭转、上半身略后仰；头略微抬起看向观者。")
rep("右侧·大头：脸偏四分之三侧，头轻轻倾斜；一只手抬到嘴边／下巴附近，手指自然收拢，指尖靠近下唇但不要遮住嘴；另一只手不在这个视图内。",
    "右侧·大头：**身体侧转约四分之三**（不要正面朝前）；脸偏四分之三侧、头轻轻倾斜；"
    "一只手抬到嘴边但不碰到嘴，手指自然收拢、**指尖朝上**；另一只手不在这个视图内。")

# ---- 4) 头饰不要三份一模一样 ----
rep("· **头顶那套饰物**：一条云朵状的饰带横在头顶，饰带上方有两枚并排的小发夹（一枚偏粉、一枚偏蓝），",
    "· **头顶那套饰物（三格不要摆得一模一样）**：至少有一格让一部分头发挡住它，"
    "或者让它的角度与被外框裁切的程度不同；不要三格都端端正正地摆出同一个花环。"
    "构成是：一条云朵状的饰带横在头顶，饰带上方有两枚并排的小发夹（一枚偏粉、一枚偏蓝），")

# ---- 5) 负向补"死板" ----
rep("**发型**：不要披发、不要把头发全散开、不要没有马尾、不要把高马尾画成低马尾或双马尾；",
    "**死板**：不要把三格画成同一套模板的三份拷贝、不要让三格的头一样大、不要让三格的头顶在同一水平线、"
    "不要让三格的表情都是笑脸、不要让三格的视线都看向观者、不要让两只手都五指全张、"
    "不要让两只手一样大或对称、不要三格都正面站直；\n"
    "**发型**：不要披发、不要把头发全散开、不要没有马尾、不要把高马尾画成低马尾或双马尾；")

out = HERE / "prompt_threeview_v6.txt"
out.write_text(t, encoding="utf-8")
print(f"wrote {out.name}  {src_len} -> {len(t)} chars")
for k in ["三格的个头必须差得很大", "不要三格都是笑脸", "三格的视线各不相同",
          "另一只手半握或收在胸前", "身体侧转约四分之三", "三格不要摆得一模一样",
          "不要三格画成同一套模板的三份拷贝", "背景**大面积纯白**"]:
    print(f"  {'OK  ' if k in t else 'MISS'} {k}")
