"""由 v2 生成 v3：收紧"手稿感"的适用范围，并把背景拉回图2 的"大片纯白＋外框"。

问题：v2 里"手稿感"这条被模型理解成"到处画线"，背景出现成片交叉排线 → 背景脏，
与图2 不符（图2 背景是大片纯白，只有人物线条密）。
修法：手稿感**限域**到线条本身；背景明确要求留白。
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
src = (HERE / "prompt_threeview_v2.txt").read_text(encoding="utf-8")
t = src

# ---- 1) 替换「手稿感」整块：限域 + 新增「背景」块 ----
start = t.index("【手稿感（本版新增，必须做到）】")
end_anchor = "不要把画面修得光滑干净。）"
end = t.index(end_anchor) + len(end_anchor)

new_block = """【手稿感（收紧版：只允许出现在线条本身，**不许扩散到背景**）】
这张要有手绘原稿的**笔迹感**，但"笔迹感"指的是**线条**，不是"到处画线"：
· 线条的粗细**不匀**：同一笔之内要有压力变化，起收干净、有笔锋，松而不僵；
· 允许有**极少量、极淡**的结构辅助线——局部、零散、几乎看不见的程度；
· 局部可以有轻微的描改痕。
**仅此而已。** 不要把"手稿感"理解成往画面里加线。

【背景（本版重点：必须回到画法图那样的"干净"）】
· 背景**大面积纯白**，只在外面留那一圈外框；
· 背景里**不要任何排线、不要交叉涂线、不要成片的灰调、不要草稿式的乱线、不要斜线阴影**；
· 人物以外的地方就让它空着；宁可空，不要脏。
· 人物的**头发用浅灰＋成组细平行排线**，**不要交叉排线、不要压深、不要大块黑色**；
  衣服的网点也要**稀而匀**，不要糊成灰块。
（判断标准：把画面缩小看，背景应当是白的；如果缩略图上背景是灰的，就是画脏了。）"""

t = t[:start] + new_block + t[end:]

# ---- 2) 画法段的 SURFACE 收紧 ----
t = t.replace(
    "SURFACE：纸面干净但不光滑，带极淡的颗粒；不要彩色、不要光晕、不要虚化。",
    "SURFACE：纸面干净、以白为主，可以带极淡的颗粒；**背景区域保持留白**，不要排线；不要彩色、不要光晕、不要虚化。"
)

# ---- 3) 负向：把手稿感那条改写成"限域"版本，并补背景干净相关 ----
t = t.replace(
    "**手稿感**：不要光滑干净的数码感、不要把铅笔底线与辅助线擦得一干二净、不要全程等粗的线条；",
    "**手稿感（限域）**：不要光滑到没有笔迹的数码感、不要全程等粗的线条；"
    "**但也不要把手稿感画成加线**——不要背景排线、不要交叉涂线、不要背景成片灰调、不要草稿式乱线、不要斜线阴影；"
)
t = t.replace(
    "不要把头发压成深灰或大块黑色、不要把白色上衣填成中灰；",
    "不要把头发压成深灰或大块黑色、不要把头发画成交叉排线、不要把白色上衣填成中灰、不要把网点糊成灰块；"
)
t = t.replace(
    "不要画成\"人物设定表\"那种整齐并排。",
    "不要画成\"人物设定表\"那种整齐并排。",
)

out = HERE / "prompt_threeview_v3.txt"
out.write_text(t, encoding="utf-8")
print(f"wrote {out.name}  {len(src)} -> {len(t)} chars")
print("校验：")
for k in ["只允许出现在线条本身", "背景**大面积纯白**", "不要背景排线", "不要交叉排线"]:
    print(f"  {'OK ' if k in t else 'MISS'} {k}")
