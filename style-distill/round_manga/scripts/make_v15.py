"""由 v14 生成 v15：B 方案验证后的两处修正，然后用于 A 方案（2K 横）。

B 的验证结果（1:1 网格读数）：
  · 头身比 约 6.5 → **约 7.4**（颅顶到下巴占全高 15.5% → 13.5%）✓ 体格模块有效
  · 肩宽／头宽 改善 ✓
  · 但 **腿只占 43%**（目标是一半以上）✗
  · 且**出现蓝色染色**：彩度 0.5 → **1.1**，荷叶边与裙子肉眼可见发蓝 ✗
所以本版补两处，其余逐字继承 v14。
"""
from pathlib import Path

HERE = Path(__file__).resolve().parent
t = (HERE / "prompt_threeview_v14.txt").read_text(encoding="utf-8")
src_len = len(t)


def rep(old: str, new: str) -> None:
    global t
    assert t.count(old) == 1, f"锚点未唯一命中({t.count(old)}): {old[:44]}"
    t = t.replace(old, new, 1)


# ---- 1) 腿长：从"一半或略多"改成硬指标 ----
rep("**腿**：从胯到脚约为身高的 **一半或略多**，腿要**长**；小腿明显长于大腿的视觉印象不要反过来；",
    "**腿（本版加强）**：从胯到脚约为身高的 **55%**——腿要**明显长于躯干**，"
    "上身（肩到胯）只占约 45%；小腿略长于大腿；**不要五五分的短腿**；")

# ---- 2) 中性灰：补正向与负向（治蓝色染色）----
rep("【本轮显式授权：黑白】\n本次是有意做成**黑白漫画原稿**，因此允许并**要求**维持无彩色。这是本轮唯一的例外。",
    "【本轮显式授权：黑白 —— 必须是**中性灰**，不许有任何色相】\n"
    "本次是有意做成**黑白漫画原稿**，因此要求维持无彩色。这是本轮唯一的例外。\n"
    "**而且必须是「中性」的黑白**：整幅的灰阶**不带任何色相**——"
    "**不要偏蓝、不要偏冷、不要把荷叶边或裙子染成蓝灰**；"
    "所有灰阶都来自同一条中性灰阶（R=G=B）。")

rep("**体格（本版重点）**：不要大头小身、不要画成 5 头身、",
    "**中性灰（本版重点）**：不要任何色相、不要偏蓝或偏冷、不要把荷叶边／裙子／头发染上颜色、"
    "不要彩色网点；所有灰阶必须 R=G=B；\n"
    "**腿长（本版加强）**：不要五五分的短腿、不要让上身长于下身、不要让腿短于躯干；\n"
    "**体格**：不要大头小身、不要画成 5 头身、")

out = HERE / "prompt_threeview_v15.txt"
out.write_text(t, encoding="utf-8")
print(f"wrote {out.name}  {src_len} -> {len(t)} chars")
for k in ["必须是**中性灰**，不许有任何色相", "不要偏蓝、不要偏冷", "所有灰阶必须 R=G=B",
          "约为身高的 **55%**", "不要五五分的短腿", "**7 个头高**"]:
    print(f"  {'OK  ' if k in t else 'MISS'} {k}")
